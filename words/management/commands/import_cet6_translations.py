def _make_title(genre):
    return f'六级段落翻译 {genre}'


def import_cet6_translations(verbose=True):
    created = 0
    updated = 0

    def upsert(year, genre, content, note, tags, reference_answer=''):
        nonlocal created, updated
        title = _make_title(genre)
        obj, was_created = ExamQuestion.objects.update_or_create(
            exam_type='cet6', year=year, question_type='translation', genre=genre,
            defaults={
                'title': title,
                'content': content,
                'prompt': '将下列中文段落翻译成英文（满分 15 分）\n' + note,
                'model_answer': reference_answer or '',
                'tags': tags,
                'is_imported': True,
            },
        )
        if was_created:
            created += 1
        else:
            updated += 1

    for row in CET6_TRANSLATION:
        if len(row) == 5:
            year, genre, content, note, tags = row
            reference_answer = ''
        else:
            year, genre, content, note, tags, reference_answer = row
        upsert(year, genre, content, note, tags, reference_answer)

    if verbose:
        print(f'六级翻译导入完成：新增 {created} 条，更新 {updated} 条')
        total = ExamQuestion.objects.filter(exam_type='cet6', question_type='translation').count()
        print(f'当前六级翻译真题总数：{total}')
        years = ExamQuestion.objects.filter(exam_type='cet6', question_type='translation').values_list('year', flat=True).distinct().order_by('-year')
        for y in years:
            cnt = ExamQuestion.objects.filter(exam_type='cet6', question_type='translation', year=y).count()
            print(f'  {y}年: {cnt} 条')


class Command(BaseCommand):
    help = '导入大学英语六级段落翻译真题（2020-2026，共 43 条）'

    def handle(self, *args, **options):
        import_cet6_translations()
